import { gzipSync } from 'node:zlib';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';

const [inputDirArg, outputFileArg] = process.argv.slice(2);

if (!inputDirArg || !outputFileArg) {
  console.error('Usage: node scripts/generate-esp32-web-assets.mjs <dist-dir> <output-header>');
  process.exit(1);
}

const inputDir = resolve(inputDirArg);
const outputFile = resolve(outputFileArg);

const mimeTypes = new Map([
  ['.html', 'text/html; charset=utf-8'],
  ['.js', 'text/javascript; charset=utf-8'],
  ['.mjs', 'text/javascript; charset=utf-8'],
  ['.css', 'text/css; charset=utf-8'],
  ['.json', 'application/json; charset=utf-8'],
  ['.webmanifest', 'application/manifest+json; charset=utf-8'],
  ['.svg', 'image/svg+xml; charset=utf-8'],
  ['.png', 'image/png'],
  ['.jpg', 'image/jpeg'],
  ['.jpeg', 'image/jpeg'],
  ['.webp', 'image/webp'],
  ['.ico', 'image/x-icon'],
  ['.wasm', 'application/wasm'],
  ['.txt', 'text/plain; charset=utf-8'],
]);

const gzipExtensions = new Set([
  '.html',
  '.js',
  '.mjs',
  '.css',
  '.json',
  '.webmanifest',
  '.svg',
  '.txt',
]);

function walk(dir) {
  return readdirSync(dir)
    .flatMap((entry) => {
      const path = join(dir, entry);
      const stats = statSync(path);

      if (stats.isDirectory()) {
        return walk(path);
      }

      return path;
    })
    .sort();
}

function toRoutePath(filePath) {
  return `/${relative(inputDir, filePath).split(sep).join('/')}`;
}

function toSymbolName(routePath, index) {
  const stem = routePath
    .replace(/^\//, '')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();

  return `asset_${stem || 'root'}_${index}`;
}

function toByteArray(buffer) {
  const bytes = [];

  for (let offset = 0; offset < buffer.length; offset += 16) {
    const line = Array.from(buffer.subarray(offset, offset + 16), (byte) => `0x${byte.toString(16).padStart(2, '0')}`);
    bytes.push(`  ${line.join(', ')},`);
  }

  return bytes.join('\n');
}

const files = walk(inputDir);
const assets = files.map((filePath, index) => {
  const routePath = toRoutePath(filePath);
  const ext = extname(filePath).toLowerCase();
  const raw = readFileSync(filePath);
  const zipped = gzipExtensions.has(ext) ? gzipSync(raw, { level: 9 }) : raw;
  const shouldGzip = gzipExtensions.has(ext) && zipped.length < raw.length;

  return {
    routePath,
    symbol: toSymbolName(routePath, index),
    mimeType: mimeTypes.get(ext) || 'application/octet-stream',
    data: shouldGzip ? zipped : raw,
    originalSize: raw.length,
    gzip: shouldGzip,
  };
});

const totalOriginal = assets.reduce((sum, asset) => sum + asset.originalSize, 0);
const totalEmbedded = assets.reduce((sum, asset) => sum + asset.data.length, 0);

const lines = [
  '#pragma once',
  '',
  '#include <Arduino.h>',
  '',
  '// Generated by scripts/generate-esp32-web-assets.mjs',
  `// Source: ${relative(dirname(outputFile), inputDir)}`,
  `// Assets: ${assets.length}`,
  `// Original bytes: ${totalOriginal}`,
  `// Embedded bytes: ${totalEmbedded}`,
  '',
  'namespace HelioSyncWebAssets {',
  '',
  'struct Asset {',
  '  const char* path;',
  '  const char* mimeType;',
  '  const uint8_t* data;',
  '  const size_t size;',
  '  const bool gzip;',
  '};',
  '',
];

for (const asset of assets) {
  lines.push(`const uint8_t ${asset.symbol}[] PROGMEM = {`);
  lines.push(toByteArray(asset.data));
  lines.push('};');
  lines.push('');
}

lines.push('const Asset assets[] = {');

for (const asset of assets) {
  lines.push(`  { "${asset.routePath}", "${asset.mimeType}", ${asset.symbol}, sizeof(${asset.symbol}), ${asset.gzip ? 'true' : 'false'} },`);
}

lines.push('};');
lines.push('');
lines.push('const size_t assetCount = sizeof(assets) / sizeof(assets[0]);');
lines.push('');
lines.push('}  // namespace HelioSyncWebAssets');
lines.push('');

mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, lines.join('\n'));

console.log(`Embedded ${assets.length} assets into ${outputFileArg}`);
console.log(`Original: ${(totalOriginal / 1024).toFixed(1)} KB`);
console.log(`Embedded: ${(totalEmbedded / 1024).toFixed(1)} KB`);
